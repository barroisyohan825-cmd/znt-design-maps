-- ZNT DESIGN MAPS : à exécuter dans Supabase > SQL Editor.
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  pseudo text not null check (char_length(pseudo) between 1 and 40),
  type text not null check (char_length(type) between 1 and 80),
  details text not null check (char_length(details) between 1 and 1200),
  contact text not null check (char_length(contact) between 1 and 80),
  status text not null default 'En attente' check (status in ('En attente','En cours','Terminée')),
  created_at timestamptz not null default now()
);
alter table public.orders enable row level security;
-- Le public peut uniquement envoyer une demande. Il ne peut ni lire ni modifier les commandes.
drop policy if exists "Public can submit orders" on public.orders;
create policy "Public can submit orders" on public.orders for insert to anon with check (
  char_length(pseudo) between 1 and 40 and char_length(type) between 1 and 80 and
  char_length(details) between 1 and 1200 and char_length(contact) between 1 and 80 and status = 'En attente'
);
-- Seuls les comptes authentifiés peuvent lire/modifier/supprimer.
-- Désactive les inscriptions publiques dans Supabase Auth et crée uniquement ton propre compte.
drop policy if exists "Admin can read orders" on public.orders;
create policy "Admin can read orders" on public.orders for select to authenticated using (true);
drop policy if exists "Admin can update orders" on public.orders;
create policy "Admin can update orders" on public.orders for update to authenticated using (true) with check (true);
drop policy if exists "Admin can delete orders" on public.orders;
create policy "Admin can delete orders" on public.orders for delete to authenticated using (true);
